-- Replace closed reason enums with catalog-backed codes while preserving existing values.
ALTER TABLE "quotes"
  ALTER COLUMN "rejection_reason" TYPE VARCHAR(80) USING "rejection_reason"::TEXT,
  ALTER COLUMN "cancellation_reason" TYPE VARCHAR(80) USING "cancellation_reason"::TEXT,
  ALTER COLUMN "approval_return_reason" TYPE VARCHAR(80) USING "approval_return_reason"::TEXT,
  ALTER COLUMN "revision_reason" TYPE VARCHAR(80) USING "revision_reason"::TEXT,
  ADD COLUMN "commercial_conditions" TEXT;

DROP TYPE "QuoteRejectionReason";
DROP TYPE "QuoteCancellationReason";
DROP TYPE "QuoteApprovalReturnReason";
DROP TYPE "QuoteRevisionReason";

CREATE TYPE "QuoteCatalogType" AS ENUM (
  'VALIDITY_DAYS',
  'PAYMENT_TERMS',
  'COMMERCIAL_CONDITIONS',
  'DELIVERY_TIME',
  'REVISION_REASON',
  'REJECTION_REASON',
  'CANCELLATION_REASON',
  'APPROVAL_RETURN_REASON'
);

CREATE TABLE "quote_catalog_options" (
  "id" UUID NOT NULL,
  "type" "QuoteCatalogType" NOT NULL,
  "code" VARCHAR(80) NOT NULL,
  "label" VARCHAR(260) NOT NULL,
  "value" TEXT,
  "numeric_value" INTEGER,
  "requires_comment" BOOLEAN NOT NULL DEFAULT false,
  "sort_order" INTEGER NOT NULL DEFAULT 0,
  "is_active" BOOLEAN NOT NULL DEFAULT true,
  "branch_id" UUID,
  "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "quote_catalog_options_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "quote_catalog_options_type_code_branch_id_key" ON "quote_catalog_options"("type", "code", "branch_id");
CREATE INDEX "quote_catalog_options_type_is_active_idx" ON "quote_catalog_options"("type", "is_active");
CREATE INDEX "quote_catalog_options_branch_id_idx" ON "quote_catalog_options"("branch_id");

ALTER TABLE "quote_catalog_options"
  ADD CONSTRAINT "quote_catalog_options_branch_id_fkey"
  FOREIGN KEY ("branch_id") REFERENCES "branches"("id") ON DELETE CASCADE ON UPDATE CASCADE;

